"""
Locust load/stress generator for the GoodVolunteer API.

Scenarios (weighted to look like real traffic):
  * browse events (most common)
  * view a single event
  * register a volunteer
  * admin: create an event, occasionally delete one

Run (web UI):   locust -f locustfile.py --host http://api:5000
Run (headless): locust -f locustfile.py --host http://api:5000 --headless -u 50 -r 5 -t 5m
"""
import random
import uuid

from locust import HttpUser, task, between

CAUSES = ["Environment", "Education", "Community", "Healthcare", "Animal Welfare"]


class VolunteerUser(HttpUser):
    wait_time = between(0.5, 2.5)

    def on_start(self):
        self.email = f"user_{uuid.uuid4().hex[:8]}@example.com"
        self.name = f"User {random.randint(1, 100000)}"

    @task(10)
    def browse_events(self):
        cause = random.choice(["All"] + CAUSES)
        params = "" if cause == "All" else f"?cause={cause}"
        self.client.get(f"/api/events{params}", name="/api/events")

    @task(5)
    def view_event(self):
        eid = random.randint(1, 6)
        self.client.get(f"/api/events/{eid}", name="/api/events/:id")

    @task(6)
    def register(self):
        eid = random.randint(1, 6)
        self.client.post(
            f"/api/events/{eid}/register",
            json={"employee_name": self.name, "employee_email": self.email},
            name="/api/events/:id/register",
        )

    @task(3)
    def dashboard(self):
        self.client.get(f"/api/dashboard?email={self.email}", name="/api/dashboard?email")

    @task(1)
    def admin_create(self):
        self.client.post(
            "/api/events",
            json={
                "title": f"Load Event {uuid.uuid4().hex[:6]}",
                "description": "Generated by load test",
                "cause": random.choice(CAUSES),
                "location": "Test City",
                "date": "2026-12-01",
                "duration_hours": random.randint(2, 6),
                "max_volunteers": random.randint(20, 100),
            },
            name="/api/events [create]",
        )
